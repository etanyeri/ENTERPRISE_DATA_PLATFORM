
{{ config(materialized='table', alias='TF_SFDC_ACCOUNT') }}

SELECT
      SFA.ACCOUNT_ID AS SFDC_ACCOUNT_ID
    , SFA.ACCOUNT_NAME AS SFDC_ACCOUNT_NAME
    , SFA.ACCOUNT_NUMBER AS SFDC_ACCOUNT_NUMBER
    , SFA.ACCOUNT_TYPE AS SFDC_ACCOUNT_TYPE
    , SFA.INDUSTRY AS SFDC_INDUSTRY
    , SFA.DESCRIPTION AS SFDC_ACCOUNT_DESCRIPTION
    , SFA.PARENT_ID AS PARENT_SFDC_ACCOUNT_ID
    , COALESCE(PA.ACCOUNT_NAME, SFA.ACCOUNT_NAME) AS PARENT_SFDC_ACCOUNT_NAME
    , SFA.OWNER_ID AS SFDC_OWNER_ID
    , SFU.FIRST_NAME AS OWNER_FIRST_NAME
    , SFU.LAST_NAME AS OWNER_LAST_NAME
    , SFU.EMAIL AS OWNER_EMAIL
    , SFA.WEBSITE AS SFDC_WEBSITE
    , SFA.PHONE AS SFDC_PHONE_ORIGINAL

    , CASE
        WHEN LENGTH(REGEXP_REPLACE(COALESCE(SFA.PHONE, ''), '[^0-9]', '')) = 11
             AND LEFT(REGEXP_REPLACE(SFA.PHONE, '[^0-9]', ''), 1) = '1'
          THEN SUBSTR(REGEXP_REPLACE(SFA.PHONE, '[^0-9]', ''), 2, 10)
        WHEN LENGTH(REGEXP_REPLACE(COALESCE(SFA.PHONE, ''), '[^0-9]', '')) = 10
          THEN REGEXP_REPLACE(SFA.PHONE, '[^0-9]', '')
        ELSE NULL
      END AS SFDC_PHONE_CLEANED

    , SFA.BILLING_CITY AS SFDC_BILLING_CITY
    , SFA.BILLING_STATE AS SFDC_BILLING_STATE
    , SFA.BILLING_COUNTRY AS SFDC_BILLING_COUNTRY
    , CASE
        WHEN UPPER(TRIM(SFA.BILLING_COUNTRY)) IN ('US', 'USA', 'UNITED STATES', 'UNITED STATES OF AMERICA') THEN 'US'
        WHEN UPPER(TRIM(SFA.BILLING_COUNTRY)) IN ('CA', 'CAN', 'CANADA') THEN 'CA'
        ELSE UPPER(TRIM(SFA.BILLING_COUNTRY))
      END AS SFDC_BILLING_COUNTRY_CODE

    , SFA.SHIPPING_CITY AS SFDC_SHIPPING_CITY
    , SFA.SHIPPING_STATE AS SFDC_SHIPPING_STATE
    , SFA.SHIPPING_COUNTRY AS SFDC_SHIPPING_COUNTRY
    , SFA.ANNUAL_REVENUE AS SFDC_ANNUAL_REVENUE
    , SFA.NUMBER_OF_EMPLOYEES AS SFDC_NUMBER_OF_EMPLOYEES
    , SFA.RATING AS SFDC_RATING
    , SFA.OWNERSHIP AS SFDC_OWNERSHIP
    , COALESCE(SFA.PARENT_ID, SFA.ACCOUNT_ID) AS SFDC_ACCOUNT_HIERARCHY_ID
    , CASE WHEN SFA.PARENT_ID IS NULL THEN 'PARENT' ELSE 'CHILD' END AS SFDC_ACCOUNT_HIERARCHY_TYPE
    , SFA.CREATED_DATE AS SFDC_CREATED_DATE
    , SFA.LAST_MODIFIED_DATE AS SFDC_LAST_MODIFIED_DATE
    , SFA.IS_DELETED AS SFDC_IS_DELETED

FROM {{ source('salesforce_ingest', 'account') }} AS SFA
      
LEFT OUTER JOIN {{ source('salesforce_ingest', 'account') }} AS PA ON SFA.PARENT_ID = PA.ACCOUNT_ID AND COALESCE(PA.IS_DELETED, FALSE) = FALSE
LEFT OUTER JOIN {{ source('salesforce_ingest', 'user') }} AS SFU ON SFA.OWNER_ID = SFU.USER_ID

WHERE UPPER(TRIM(SFA.BILLING_COUNTRY)) IN
    ('US', 'USA', 'UNITED STATES', 'UNITED STATES OF AMERICA', 'CA', 'CAN', 'CANADA')
    AND COALESCE(SFA.IS_DELETED, FALSE) = FALSE

QUALIFY ROW_NUMBER() OVER (
    PARTITION BY SFA.ACCOUNT_ID
    ORDER BY SFA.LAST_MODIFIED_DATE DESC NULLS LAST,
             PA.LAST_MODIFIED_DATE DESC NULLS LAST
) = 1
