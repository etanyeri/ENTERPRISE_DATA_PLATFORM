SELECT
      O.OPPORTUNITY_ID AS SFDC_OPPORTUNITY_ID
    , O.OPPORTUNITY_NAME AS SFDC_OPPORTUNITY_NAME
    , O.ACCOUNT_ID AS SFDC_ACCOUNT_ID
    , A.ACCOUNT_NAME AS SFDC_ACCOUNT_NAME
    , A.PARENT_ID AS PARENT_SFDC_ACCOUNT_ID
    , P.ACCOUNT_NAME AS PARENT_SFDC_ACCOUNT_NAME
    , O.OWNER_ID AS SFDC_OWNER_ID
    , U.FIRST_NAME AS OWNER_FIRST_NAME
    , U.LAST_NAME AS OWNER_LAST_NAME
    , U.EMAIL AS OWNER_EMAIL
    , O.STAGE_NAME AS OPPORTUNITY_STAGE
    , O.OPPORTUNITY_TYPE AS OPPORTUNITY_TYPE
    , O.LEAD_SOURCE AS LEAD_SOURCE
    , O.DESCRIPTION AS OPPORTUNITY_DESCRIPTION
    , O.AMOUNT::NUMBER(18,2) AS OPPORTUNITY_AMOUNT
    , O.PROBABILITY::NUMBER(5,2) AS WIN_PROBABILITY
    , O.EXPECTED_REVENUE::NUMBER(18,2) AS EXPECTED_REVENUE
    , O.CURRENCY_ISO_CODE AS CURRENCY_CODE
    , O.CREATED_DATE AS CREATED_DATE
    , O.CLOSE_DATE AS CLOSE_DATE
    , O.LAST_MODIFIED_DATE AS LAST_MODIFIED_DATE
    , O.IS_CLOSED AS IS_CLOSED
    , O.IS_WON AS IS_WON
    , CASE
        WHEN O.IS_WON = TRUE THEN 'CLOSED_WON'
        WHEN O.IS_CLOSED = TRUE THEN 'CLOSED_LOST'
        ELSE 'OPEN'
      END AS OPPORTUNITY_STATUS
    , CASE
        WHEN O.AMOUNT >= 1000000 THEN 'ENTERPRISE'
        WHEN O.AMOUNT >= 100000 THEN 'MID_MARKET'
        ELSE 'SMB'
      END AS DEAL_SIZE_SEGMENT
    , CASE
        WHEN O.IS_CLOSED = FALSE AND O.CLOSE_DATE < CURRENT_DATE() THEN TRUE
        ELSE FALSE
      END AS IS_OVERDUE
    , DATEDIFF('day', O.CREATED_DATE, O.CLOSE_DATE) AS SALES_CYCLE_DAYS
    , CURRENT_TIMESTAMP() AS UPDATED_AT

FROM {{ source('salesforce_ingest', 'opportunity') }} AS O
LEFT OUTER JOIN {{ source('salesforce_ingest', 'account') }} AS A ON O.ACCOUNT_ID = A.ACCOUNT_ID
LEFT OUTER JOIN {{ source('salesforce_ingest', 'account') }} AS P ON A.PARENT_ID = P.ACCOUNT_ID
LEFT OUTER JOIN {{ source('salesforce_ingest', 'user') }} AS U ON O.OWNER_ID = U.USER_ID

WHERE COALESCE(O.IS_DELETED, FALSE) = FALSE

QUALIFY ROW_NUMBER() OVER (
    PARTITION BY O.OPPORTUNITY_ID
    ORDER BY O.LAST_MODIFIED_DATE DESC NULLS LAST
) = 1
