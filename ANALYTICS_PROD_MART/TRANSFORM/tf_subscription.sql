WITH SUBSCRIPTION_BASE AS (

    SELECT
          S.SUBSCRIPTION_ID
        , S.ACCOUNT_ID
        , S.CONTRACT_ID
        , S.OPPORTUNITY_ID
        , S.PRODUCT_ID
        , S.SUBSCRIPTION_NUMBER
        , S.SUBSCRIPTION_STATUS
        , S.START_DATE
        , S.END_DATE
        , S.BILLING_FREQUENCY
        , S.CURRENCY_CODE
        , S.QUANTITY
        , S.UNIT_PRICE
        , S.DISCOUNT_PERCENT
        , S.LAST_MODIFIED_DATE
    FROM {{ source('billing_ingest', 'subscription') }} AS S
    WHERE COALESCE(S.IS_DELETED, FALSE) = FALSE
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY S.SUBSCRIPTION_ID
        ORDER BY S.LAST_MODIFIED_DATE DESC NULLS LAST
    ) = 1

)

SELECT
      S.SUBSCRIPTION_ID
    , S.SUBSCRIPTION_NUMBER
    , S.SUBSCRIPTION_STATUS
    , S.ACCOUNT_ID
    , A.ACCOUNT_NAME
    , S.CONTRACT_ID
    , C.CONTRACT_NUMBER
    , C.CONTRACT_STATUS
    , S.OPPORTUNITY_ID
    , O.OPPORTUNITY_NAME
    , O.OPPORTUNITY_STAGE
    , O.SFDC_OWNER_ID AS OPPORTUNITY_OWNER_ID
    , S.PRODUCT_ID
    , P.PRODUCT_NAME
    , P.PRODUCT_CATEGORY
    , S.START_DATE
    , S.END_DATE
    , DATEDIFF('month', S.START_DATE, S.END_DATE) AS SUBSCRIPTION_TERM_MONTHS
    , S.BILLING_FREQUENCY
    , S.CURRENCY_CODE
    , S.QUANTITY
    , S.UNIT_PRICE::NUMBER(18,2) AS UNIT_PRICE
    , S.DISCOUNT_PERCENT::NUMBER(5,2) AS DISCOUNT_PERCENT
    , ROUND(S.QUANTITY * S.UNIT_PRICE * (1 - COALESCE(S.DISCOUNT_PERCENT, 0) / 100), 2) AS NET_BILLING_AMOUNT
    , CASE
        WHEN UPPER(S.BILLING_FREQUENCY) = 'MONTHLY' THEN 12
        WHEN UPPER(S.BILLING_FREQUENCY) = 'QUARTERLY' THEN 4
        WHEN UPPER(S.BILLING_FREQUENCY) = 'ANNUAL' THEN 1
        ELSE NULL
      END AS BILLING_PERIODS_PER_YEAR
    , S.LAST_MODIFIED_DATE
    , CURRENT_TIMESTAMP() AS UPDATED_AT

FROM SUBSCRIPTION_BASE AS S
LEFT OUTER JOIN {{ ref('DIM_ACCOUNT') }} AS A ON S.ACCOUNT_ID = A.ACCOUNT_ID
LEFT OUTER JOIN {{ ref('dim_contract') }} AS C ON S.CONTRACT_ID = C.CONTRACT_ID
LEFT OUTER JOIN {{ ref('TF_OPPORTUNITY') }} AS O ON S.OPPORTUNITY_ID = O.SFDC_OPPORTUNITY_ID
LEFT OUTER JOIN {{ ref('dim_product') }} AS P ON S.PRODUCT_ID = P.PRODUCT_ID
