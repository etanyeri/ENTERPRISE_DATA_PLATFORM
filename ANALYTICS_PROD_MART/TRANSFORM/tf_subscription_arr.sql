
SELECT
      REPORT_DATE::DATE AS REPORT_DATE
    , SUBSCRIPTION_ID
    , ACCOUNT_ID
    , PRODUCT_ID
    , CONTRACT_ID
    , OPPORTUNITY_ID
    , ARR_USD::NUMBER(18,2) AS ARR_USD
    , ARR_LOCAL::NUMBER(18,2) AS ARR_LOCAL
    , UPPER(TRIM(LOCAL_CURRENCY)) AS LOCAL_CURRENCY
    , SOURCE
FROM {{ ref('subscription_arr_seed') }}
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY REPORT_DATE, SUBSCRIPTION_ID
    ORDER BY SUBSCRIPTION_ID
) = 1
