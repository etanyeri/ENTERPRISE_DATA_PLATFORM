
SELECT
      {{ dbt_utils.generate_surrogate_key(['SUBSCRIPTION_ID']) }} AS SUBSCRIPTION_KEY
    , SUBSCRIPTION_ID
    , ACCOUNT_ID
    , PRODUCT_ID
    , MIN(REPORT_DATE) AS FIRST_REPORT_DATE
    , MAX(REPORT_DATE) AS LAST_REPORT_DATE
    , MAX_BY(LOCAL_CURRENCY, REPORT_DATE) AS LOCAL_CURRENCY
FROM {{ ref('tf_subscription_arr') }}
GROUP BY SUBSCRIPTION_ID, ACCOUNT_ID, PRODUCT_ID
