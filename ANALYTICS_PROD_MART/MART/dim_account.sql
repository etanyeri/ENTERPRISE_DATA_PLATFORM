
SELECT
      {{ dbt_utils.generate_surrogate_key(['A.SFDC_ACCOUNT_ID']) }} AS ACCOUNT_SK
    , A.SFDC_ACCOUNT_ID AS ACCOUNT_ID
    , A.SFDC_ACCOUNT_NAME AS ACCOUNT_NAME
    , A.SFDC_ACCOUNT_NUMBER AS ACCOUNT_NUMBER
    , A.SFDC_ACCOUNT_TYPE AS ACCOUNT_TYPE
    , A.SFDC_INDUSTRY AS INDUSTRY
    , A.SFDC_ACCOUNT_DESCRIPTION AS ACCOUNT_DESCRIPTION
    , A.PARENT_SFDC_ACCOUNT_ID AS PARENT_ACCOUNT_ID
    , A.PARENT_SFDC_ACCOUNT_NAME AS PARENT_ACCOUNT_NAME
    , A.SFDC_ACCOUNT_HIERARCHY_ID AS ACCOUNT_HIERARCHY_ID
    , A.SFDC_ACCOUNT_HIERARCHY_TYPE AS ACCOUNT_HIERARCHY_TYPE
    , A.SFDC_OWNER_ID AS OWNER_ID
    , A.OWNER_FIRST_NAME
    , A.OWNER_LAST_NAME
    , A.OWNER_EMAIL
    , A.SFDC_WEBSITE AS WEBSITE
    , A.SFDC_PHONE_CLEANED AS PHONE
    , A.SFDC_BILLING_CITY AS BILLING_CITY
    , A.SFDC_BILLING_STATE AS BILLING_STATE
    , A.SFDC_BILLING_COUNTRY_CODE AS BILLING_COUNTRY
    , A.SFDC_SHIPPING_CITY AS SHIPPING_CITY
    , A.SFDC_SHIPPING_STATE AS SHIPPING_STATE
    , A.SFDC_SHIPPING_COUNTRY AS SHIPPING_COUNTRY
    , A.SFDC_ANNUAL_REVENUE AS ANNUAL_REVENUE
    , A.SFDC_NUMBER_OF_EMPLOYEES AS NUMBER_OF_EMPLOYEES
    , A.SFDC_RATING AS ACCOUNT_RATING
    , A.SFDC_OWNERSHIP AS OWNERSHIP
    , A.SFDC_CREATED_DATE AS CREATED_DATE
    , A.SFDC_LAST_MODIFIED_DATE AS LAST_MODIFIED_DATE

    , CASE
        WHEN A.SFDC_ANNUAL_REVENUE >= 10000000 THEN 'ENTERPRISE'
        WHEN A.SFDC_ANNUAL_REVENUE >= 1000000 THEN 'MID_MARKET'
        WHEN A.SFDC_ANNUAL_REVENUE IS NOT NULL THEN 'SMB'
        ELSE 'UNKNOWN'
      END AS REVENUE_SEGMENT

    , CASE
        WHEN A.PARENT_SFDC_ACCOUNT_ID IS NULL THEN TRUE
        ELSE FALSE
      END AS IS_PARENT_ACCOUNT

    , CURRENT_TIMESTAMP() AS DBT_UPDATED_AT

FROM {{ ref('TF_SFDC_ACCOUNT') }} AS A
