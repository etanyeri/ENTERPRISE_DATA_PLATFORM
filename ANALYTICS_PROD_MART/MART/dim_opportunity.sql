SELECT
      {{ dbt_utils.generate_surrogate_key(['O.SFDC_OPPORTUNITY_ID']) }} AS OPPORTUNITY_KEY
    , O.SFDC_OPPORTUNITY_ID
    , O.SFDC_OPPORTUNITY_NAME AS OPPORTUNITY_NAME
    , O.SFDC_ACCOUNT_ID
    , O.SFDC_ACCOUNT_NAME AS ACCOUNT_NAME
    , O.PARENT_SFDC_ACCOUNT_ID
    , O.SFDC_OWNER_ID
    , O.OWNER_FIRST_NAME
    , O.OWNER_LAST_NAME
    , O.OPPORTUNITY_STAGE
    , O.OPPORTUNITY_TYPE
    , O.OPPORTUNITY_STATUS
    , O.LEAD_SOURCE
    , O.DEAL_SIZE_SEGMENT
    , O.CURRENCY_CODE
    , O.CREATED_DATE
    , O.CLOSE_DATE
    , O.IS_CLOSED
    , O.IS_WON
    , CURRENT_TIMESTAMP() AS UPDATED_AT
FROM {{ ref('TF_OPPORTUNITY') }} AS O
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY OPPORTUNITY_ID
    ORDER BY LAST_MODIFIED_DATE DESC NULLS LAST
) = 1

