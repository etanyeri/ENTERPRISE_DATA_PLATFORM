SELECT
      {{ dbt_utils.generate_surrogate_key(['TF.SFDC_OPPORTUNITY_ID']) }} AS OPPORTUNITY_FACT_KEY
    , COALESCE(OPP.OPPORTUNITY_KEY, {{ dbt_utils.generate_surrogate_key(["'-1'"]) }}) AS OPPORTUNITY_KEY
    , COALESCE(ACC.ACCOUNT_SK, {{ dbt_utils.generate_surrogate_key(["'-1'"]) }}) AS ACCOUNT_KEY
    , TF.SFDC_OPPORTUNITY_ID
    , TF.SFDC_ACCOUNT_ID
    , TF.CREATED_DATE
    , TF.CLOSE_DATE
    , TF.OPPORTUNITY_AMOUNT::NUMBER(18,2) AS OPPORTUNITY_AMOUNT
    , TF.WIN_PROBABILITY
    , TF.EXPECTED_REVENUE::NUMBER(18,2) AS EXPECTED_REVENUE
    , TF.SALES_CYCLE_DAYS
    , IFF(TF.IS_WON = TRUE, 1, 0) AS WON_OPPORTUNITY_COUNT
    , IFF(TF.IS_CLOSED = TRUE AND TF.IS_WON = FALSE, 1, 0) AS LOST_OPPORTUNITY_COUNT
    , IFF(TF.IS_CLOSED = FALSE, 1, 0) AS OPEN_OPPORTUNITY_COUNT
    , IFF(TF.IS_OVERDUE = TRUE, 1, 0) AS OVERDUE_OPPORTUNITY_COUNT
    , CURRENT_TIMESTAMP() AS UPDATED_AT
FROM {{ ref('TF_SFDC_OPPORTUNITY') }} AS TF
LEFT OUTER JOIN {{ ref('dimOpportunity') }} AS OPP ON TF.SFDC_OPPORTUNITY_ID = OPP.SFDC_OPPORTUNITY_ID
LEFT OUTER JOIN {{ ref('DIM_ACCOUNT') }} AS ACC ON TF.SFDC_ACCOUNT_ID = ACC.ACCOUNT_ID
