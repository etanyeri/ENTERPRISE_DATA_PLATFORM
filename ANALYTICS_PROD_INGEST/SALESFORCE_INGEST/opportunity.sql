
SELECT
      O.ID AS OPPORTUNITY_ID
    , O.ACCOUNT_ID
    , NULLIF(TRIM(O.NAME), '') AS OPPORTUNITY_NAME
    , O.OWNER_ID
    , NULLIF(TRIM(O.STAGE_NAME), '') AS STAGE_NAME
    , NULLIF(TRIM(O.TYPE), '') AS OPPORTUNITY_TYPE
    , NULLIF(TRIM(O.LEAD_SOURCE), '') AS LEAD_SOURCE
    , NULLIF(TRIM(O.DESCRIPTION), '') AS DESCRIPTION
    , O.AMOUNT
    , O.PROBABILITY
    , O.EXPECTED_REVENUE
    , O.CLOSE_DATE
    , O.IS_CLOSED
    , O.IS_WON
    , O.CURRENCY_ISO_CODE
    , O.CREATED_DATE
    , O.LAST_MODIFIED_DATE
    , O.IS_DELETED
FROM {{ source('salesforce_raw', 'opportunity') }} AS O
